"""The carrier board, exactly as placed in KiCad.

electronics/carrier/placement.json is generated by the board's build script
from board.json and the real footprints, so the casing follows the PCB rather
than a copy of its numbers. Board coordinates run x to the right and y towards
the front from the board's rear-left corner; case coordinates are the model's.
"""

import json
from functools import cache
from pathlib import Path

from waveform_one import layout
from waveform_one import parameters as p

PLACEMENT = Path(__file__).resolve().parents[3] / "electronics" / "carrier" / "placement.json"


@cache
def _data() -> dict:
    return json.loads(PLACEMENT.read_text())


def board() -> dict:
    return _data()["board"]


def parts() -> list[dict]:
    return _data()["parts"]


def bounds() -> tuple[tuple[float, float], tuple[float, float]]:
    """((x_min, x_max), (y_min, y_max)) of the board in case coordinates."""
    b = board()
    x0, y1 = b["case_left_x"], b["case_rear_y"]
    return (x0, x0 + b["width"]), (y1 - b["depth"], y1)


def to_case(x: float, y: float) -> tuple[float, float]:
    b = board()
    return b["case_left_x"] + x, b["case_rear_y"] - y


def bottom_z() -> float:
    (_, _, z_floor), _ = layout.interior_bounds()
    return z_floor + board()["standoff_height"]


def top_z() -> float:
    return bottom_z() + board()["thickness"]


def hole_centres() -> list[tuple[float, float]]:
    return [to_case(x, y) for x, y in _data()["mounting_holes"]]


def part_box(part: dict) -> tuple[tuple[float, float, float], tuple[float, float, float]]:
    """Corners of a part's courtyard extruded to its height, in case coordinates."""
    left, top, right, bottom = part["courtyard"]
    x0, y_front = to_case(left, bottom)
    x1, y_rear = to_case(right, top)
    return (x0, y_front, top_z()), (x1, y_rear, top_z() + part["height"])


def part(ref: str) -> dict:
    return next(item for item in parts() if item["ref"] == ref)


def rear_openings() -> list[tuple[str, float, float, float, float]]:
    """(ref, x_min, x_max, z_min, z_max) of each rear-facing socket's panel opening."""
    clear = p.CARRIER_OPENING_CLEARANCE.v
    openings = []
    for item in parts():
        if item["edge"] != "rear":
            continue
        (x0, _, z0), (x1, _, z1) = part_box(item)
        openings.append((item["ref"], x0 - clear, x1 + clear, z0 - clear, z1 + clear))
    return openings
