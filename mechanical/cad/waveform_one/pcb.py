"""Circuit boards inside the case, exactly as placed in KiCad.

Each board's placement.json (electronics/<board>/) is generated by that
board's build script from board.json and the real footprints, so the casing
follows the PCB rather than a copy of its numbers. Board coordinates run x to
the right and y towards the front from the board's rear-left corner; case
coordinates are the model's. Each board lies flat on floor posts.
"""

import json
from functools import cached_property
from pathlib import Path

from waveform_one import layout
from waveform_one import parameters as p

ELECTRONICS = Path(__file__).resolve().parents[3] / "electronics"


class Pcb:
    def __init__(self, folder: str):
        self.placement = ELECTRONICS / folder / "placement.json"

    @cached_property
    def _data(self) -> dict:
        return json.loads(self.placement.read_text())

    def board(self) -> dict:
        return self._data["board"]

    def parts(self) -> list[dict]:
        return self._data["parts"]

    def bounds(self) -> tuple[tuple[float, float], tuple[float, float]]:
        """((x_min, x_max), (y_min, y_max)) of the board in case coordinates."""
        b = self.board()
        x0, y1 = b["case_left_x"], b["case_rear_y"]
        return (x0, x0 + b["width"]), (y1 - b["depth"], y1)

    def to_case(self, x: float, y: float) -> tuple[float, float]:
        b = self.board()
        return b["case_left_x"] + x, b["case_rear_y"] - y

    def bottom_z(self) -> float:
        (_, _, z_floor), _ = layout.interior_bounds()
        return z_floor + self.board()["standoff_height"]

    def top_z(self) -> float:
        return self.bottom_z() + self.board()["thickness"]

    def hole_centres(self) -> list[tuple[float, float]]:
        return [self.to_case(x, y) for x, y in self._data["mounting_holes"]]

    def part_box(self, part: dict) -> tuple[tuple[float, float, float], tuple[float, float, float]]:
        """Corners of a part's courtyard extruded to its height, in case coordinates."""
        left, top, right, bottom = part["courtyard"]
        x0, y_front = self.to_case(left, bottom)
        x1, y_rear = self.to_case(right, top)
        return (x0, y_front, self.top_z()), (x1, y_rear, self.top_z() + part["height"])

    def part(self, ref: str) -> dict:
        return next(item for item in self.parts() if item["ref"] == ref)

    def rear_openings(self) -> list[tuple[str, float, float, float, float]]:
        """(ref, x_min, x_max, z_min, z_max) of each rear-facing socket's panel opening."""
        clear = p.CARRIER_OPENING_CLEARANCE.v
        openings = []
        for item in self.parts():
            if item["edge"] != "rear":
                continue
            (x0, _, z0), (x1, _, z1) = self.part_box(item)
            openings.append((item["ref"], x0 - clear, x1 + clear, z0 - clear, z1 + clear))
        return openings


CARRIER = Pcb("carrier")
LED_ADAPTER = Pcb("led-adapter")
